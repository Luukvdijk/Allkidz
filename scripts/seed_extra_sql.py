"""Generate supabase/migrations/20261011090100_seed_extra.sql from data/aanvullende-testdata.json (self-made data).
Run: python -I scripts/seed_extra_sql.py <repo root>
"""
import json, sys
from pathlib import Path

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()
x = json.loads((ROOT / "data/aanvullende-testdata.json").read_text(encoding="utf8"))

def q(v):
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"

def arr(values):
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]"

def jq(v):
    return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"

def insert(table, cols, rows):
    return f"insert into seed.{table} ({', '.join(cols)}) values\n" + ",\n".join("(" + ", ".join(r) + ")" for r in rows) + ";"

out = [
    "-- GENERATED by scripts/seed_extra_sql.py from data/aanvullende-testdata.json (ZELF GEMAAKTE fictieve aanvulling).",
    "truncate seed.requests, seed.shift_extras, seed.bags, seed.activities, seed.employee_licences, seed.client_locations, seed.clients, seed.requirements;",
    insert("requirements", ["location_type", "licences"], [[q(t), arr(l)] for t, l in x["requirementsByLocationType"].items()]),
    insert("clients", ["name"], [[q(c["name"])] for c in x["clients"]]),
    insert("client_locations", ["client", "location"], [[q(c["name"]), q(l)] for c in x["clients"] for l in c["locations"]]),
    insert("employee_licences", ["employee", "type", "expires_on"], [[q(l["employee"]), q(l["type"]), q(l["expiresOn"])] for l in x["employeeLicences"]]),
    insert("activities", ["name", "packing_list"], [[q(a["name"]), jq(a["packingList"])] for a in x["activities"]]),
    insert("bags", ["label", "activity"], [[q(b["label"]), q(b["activity"])] for b in x["bags"]]),
    insert("shift_extras", ["code", "activity", "bag", "extra_requirements"],
           [[q(s["code"]), q(s["activity"]), q(s["bag"]), arr(s["extraRequirements"])] for s in x["shiftExtras"]]),
    insert("requests", ["client", "location", "rule", "start_time", "end_time", "function", "activity", "note"],
           [[q(r["client"]), q(r["location"]), jq(r["rule"]), q(r["start"]), q(r["end"]), q(r["function"]), q(r["activity"]), q(r["note"])] for r in x["requests"]]),
]
p = ROOT / "supabase/migrations/20261011090100_seed_extra.sql"
p.write_text("\n\n".join(out) + "\n", encoding="utf8")
print("ok", p.stat().st_size, "bytes")
